using System.Globalization;
using System.Security.AccessControl;
using System.Security.Cryptography;
using System.Security.Principal;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;

return LicenseIssuer.Run(args);

internal static class LicenseIssuer
{
    private const int KeySize = 3072;
    private const int KeyDerivationIterations = 600000;
    private const string PasswordVariable = "SCHOOL_ISSUER_KEY_PASSWORD";
    private static readonly UTF8Encoding Utf8 = new(false, true);
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        RespectNullableAnnotations = true,
        RespectRequiredConstructorParameters = true,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
        WriteIndented = true
    };

    public static int Run(string[] args)
    {
        Console.OutputEncoding = new UTF8Encoding(false);
        try
        {
            if (args.Length == 0 || args[0] is "help" or "--help" or "-h" || args.Skip(1).Any(x => x is "--help" or "-h")) { Help(); return 0; }
            var options = ParseOptions(args.Skip(1).ToArray());
            return args[0] switch
            {
                "keygen" => Keygen(options),
                "issue" => Issue(options),
                _ => throw new IssuerInputException("未知命令。支持 keygen、issue；使用 --help 查看中文说明。")
            };
        }
        catch (IssuerInputException ex) { Console.Error.WriteLine("参数错误：" + ex.Message); return 2; }
        catch (JsonException) { Console.Error.WriteLine("资源文件不是符合格式的 JSON 数组；请参考 resources.example.json。所有字段均须明确填写。"); return 2; }
        catch (CryptographicException) { Console.Error.WriteLine("密钥读取或签名失败。请检查加密私钥文件、密码及密钥格式；程序未输出私钥或密码。"); return 3; }
        catch (UnauthorizedAccessException) { Console.Error.WriteLine("文件访问被拒绝。请检查供应商工作目录及输出目录的访问权限。"); return 3; }
        catch (IOException ex) { Console.Error.WriteLine("文件操作失败：" + ex.Message); return 3; }
        catch (ArgumentException ex) { Console.Error.WriteLine("输入或路径无效：" + ex.Message); return 2; }
    }

    private static int Keygen(Dictionary<string, string> options)
    {
        CheckOptions(options, ["out-dir"]);
        var directory = Path.GetFullPath(Required(options, "out-dir"));
        var privatePath = Path.Combine(directory, "issuer-private.encrypted.pem");
        var publicPath = Path.Combine(directory, "license-public.pem");
        if (File.Exists(privatePath) || File.Exists(publicPath)) throw new IssuerInputException("目标目录已有同名密钥。为避免覆盖，请选择新的空目录。");
        var password = Password(confirm: true);
        try
        {
            using var rsa = RSA.Create(KeySize);
            var privatePem = rsa.ExportEncryptedPkcs8PrivateKeyPem(password, new PbeParameters(PbeEncryptionAlgorithm.Aes256Cbc, HashAlgorithmName.SHA256, KeyDerivationIterations));
            var publicPem = rsa.ExportSubjectPublicKeyInfoPem();
            Directory.CreateDirectory(directory);
            var privateCreated = false;
            try
            {
                WriteNew(privatePath, privatePem, privateFile: true); privateCreated = true;
                WriteNew(publicPath, publicPem);
            }
            catch
            {
                // Only remove the encrypted private key generated by this invocation.
                // Never delete pre-existing files or recurse through the supplier directory.
                if (privateCreated) File.Delete(privatePath);
                throw;
            }
            Console.WriteLine($"已生成 RSA-{KeySize} 密钥对。");
            Console.WriteLine("加密私钥（仅供应商保管）：" + privatePath);
            Console.WriteLine("验签公钥（可配置到学校端）：" + publicPath);
            Console.WriteLine("公钥 SHA-256 指纹：" + Convert.ToHexString(SHA256.HashData(rsa.ExportSubjectPublicKeyInfo())));
            return 0;
        }
        finally { Array.Clear(password); }
    }

    private static int Issue(Dictionary<string, string> options)
    {
        CheckOptions(options, ["private-key", "machine-code", "resources", "output", "license-id", "expires"]);
        var privatePath = Path.GetFullPath(Required(options, "private-key"));
        var resourcesPath = Path.GetFullPath(Required(options, "resources"));
        var outputPath = Path.GetFullPath(Required(options, "output"));
        var licenseId = Required(options, "license-id").Trim();
        if (licenseId.Length is < 1 or > 100 || licenseId.Any(char.IsControl)) throw new IssuerInputException("license-id 须为 1 至 100 个非控制字符。");
        var machineCode = Required(options, "machine-code").Trim().ToUpperInvariant();
        if (!Regex.IsMatch(machineCode, "^[0-9A-F]{32}$", RegexOptions.CultureInvariant)) throw new IssuerInputException("设备特征码须为学校端许可证页面提供的 32 位十六进制字符串。");
        if (File.Exists(outputPath)) throw new IssuerInputException("输出文件已存在。为防止覆盖已签发许可证，请使用新的文件名。");
        if (!File.Exists(privatePath) || new FileInfo(privatePath).Length is < 1 or > 65536) throw new IssuerInputException("私钥文件不存在或大小不符合要求。");
        if (!File.Exists(resourcesPath) || new FileInfo(resourcesPath).Length is < 1 or > 131072) throw new IssuerInputException("资源 JSON 文件不存在或超过 128KB。");
        var resources = JsonSerializer.Deserialize<List<LicenseResource>>(File.ReadAllText(resourcesPath, Utf8), Json)
            ?? throw new IssuerInputException("资源文件须为 JSON 数组。");
        if (resources.Count is < 1 or > 100) throw new IssuerInputException("资源列表须包含 1 至 100 项。");
        if (resources.Any(x => x is null || string.IsNullOrWhiteSpace(x.Name) || x.Name.Length > 200 || string.IsNullOrWhiteSpace(x.AuthorizationCode) || x.AuthorizationCode.Length > 500 || x.Quantity < 0))
            throw new IssuerInputException("每项资源均须有 name（1–200字）、authorizationCode（1–500字）与非负整数 quantity。");
        if (resources.Select(x => x.Name.Trim()).Distinct(StringComparer.OrdinalIgnoreCase).Count() != resources.Count)
            throw new IssuerInputException("资源名称不能重复，请合并重复资源的数量后重试。");
        resources = resources.Select(x => x with { Name = x.Name.Trim(), AuthorizationCode = x.AuthorizationCode.Trim() }).ToList();
        var quotaCodes = new HashSet<string>(["TRAINING.CABINETS", "TRAINING.DEVICES", "TRAINING.NODES", "TRAINING.VMS", "TRAINING.ASSIGNMENTS"], StringComparer.Ordinal);
        if (resources.Where(x => quotaCodes.Contains(x.AuthorizationCode)).GroupBy(x => x.AuthorizationCode, StringComparer.Ordinal).Any(x => x.Count() > 1))
            throw new IssuerInputException("同一张许可证不能重复列出同一种平台配额。");
        var issuedAt = DateTime.UtcNow;
        DateTime? expiresAt = null;
        if (options.TryGetValue("expires", out var expires))
        {
            if (!DateOnly.TryParseExact(expires, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var day)) throw new IssuerInputException("expires 须使用 yyyy-MM-dd 格式。");
            // User-facing license dates are China Standard Time (UTC+08:00).
            // ExpiresAt itself is always serialized in UTC for the server verifier.
            expiresAt = new DateTimeOffset(day.ToDateTime(TimeOnly.MaxValue), TimeSpan.FromHours(8)).UtcDateTime;
            if (expiresAt <= issuedAt) throw new IssuerInputException("有效期结束日不能早于当前北京时间日期。");
        }
        var pem = File.ReadAllText(privatePath, Utf8);
        if (!pem.Contains("-----BEGIN ENCRYPTED PRIVATE KEY-----", StringComparison.Ordinal)) throw new IssuerInputException("只接受密码加密的 PKCS#8 PEM 私钥，不接受明文私钥或公钥。");
        var password = Password(confirm: false);
        try
        {
            using var rsa = RSA.Create();
            rsa.ImportFromEncryptedPem(pem, password);
            if (rsa.KeySize < 2048) throw new IssuerInputException("RSA 密钥长度不能低于 2048 位。");
            var payload = new LicensePayload(licenseId, "SchoolTraining", machineCode, issuedAt, expiresAt, resources);
            var bytes = JsonSerializer.SerializeToUtf8Bytes(payload, Json);
            var signature = rsa.SignData(bytes, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
            using var publicOnly = RSA.Create(); publicOnly.ImportSubjectPublicKeyInfo(rsa.ExportSubjectPublicKeyInfo(), out _);
            if (!publicOnly.VerifyData(bytes, signature, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1)) throw new CryptographicException("Internal signature verification failed.");
            var envelope = new LicenseEnvelope(Convert.ToBase64String(bytes), Convert.ToBase64String(signature));
            var envelopeJson = JsonSerializer.Serialize(envelope, Json);
            if (Utf8.GetByteCount(envelopeJson) > 262144) throw new IssuerInputException("许可证文件超过学校端 256KB 限制，请缩短资源名称或授权码。");
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
            WriteNew(outputPath, envelopeJson);
            Console.WriteLine("许可证已签发并完成公钥自检：" + outputPath);
            Console.WriteLine("许可证编号：" + licenseId);
            Console.WriteLine("设备特征码：" + machineCode);
            Console.WriteLine("资源项数：" + resources.Count);
            Console.WriteLine(expiresAt is null ? "有效期：未设置截止日。" : "有效期：截至北京时间 " + expiresAt.Value.AddHours(8).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture) + " 当日结束。");
            return 0;
        }
        finally { Array.Clear(password); }
    }

    private static char[] Password(bool confirm)
    {
        var environment = Environment.GetEnvironmentVariable(PasswordVariable);
        var password = environment is null ? ReadHidden("请输入私钥密码：") : environment.ToCharArray();
        if (password.Length is < 12 or > 1024) { Array.Clear(password); throw new IssuerInputException("私钥密码须为 12 至 1024 个字符。请使用独立的高强度密码。"); }
        if (confirm && environment is null)
        {
            var repeated = ReadHidden("请再次输入私钥密码：");
            try
            {
                if (!password.AsSpan().SequenceEqual(repeated)) { Array.Clear(password); throw new IssuerInputException("两次私钥密码不一致。"); }
            }
            finally { Array.Clear(repeated); }
        }
        return password;
    }

    private static char[] ReadHidden(string prompt)
    {
        if (Console.IsInputRedirected) throw new IssuerInputException("非交互调用须通过环境变量 SCHOOL_ISSUER_KEY_PASSWORD 提供私钥密码，禁止把密码放在命令行参数中。");
        Console.Error.Write(prompt);
        var value = new List<char>();
        while (true)
        {
            var key = Console.ReadKey(intercept: true);
            if (key.Key == ConsoleKey.Enter) { Console.Error.WriteLine(); return value.ToArray(); }
            if (key.Key == ConsoleKey.Backspace) { if (value.Count > 0) value.RemoveAt(value.Count - 1); continue; }
            if (key.Key == ConsoleKey.Escape || (key.Modifiers.HasFlag(ConsoleModifiers.Control) && key.Key == ConsoleKey.C)) throw new IssuerInputException("已取消输入。");
            if (!char.IsControl(key.KeyChar) && value.Count < 1024) value.Add(key.KeyChar);
        }
    }

    private static void WriteNew(string path, string content, bool privateFile = false)
    {
        var options = new FileStreamOptions { Mode = FileMode.CreateNew, Access = FileAccess.Write, Share = FileShare.None };
        if (privateFile && !OperatingSystem.IsWindows()) options.UnixCreateMode = UnixFileMode.UserRead | UnixFileMode.UserWrite;
        using (var stream = new FileStream(path, options))
        {
            var bytes = Utf8.GetBytes(content + Environment.NewLine); stream.Write(bytes); stream.Flush(flushToDisk: true);
        }
        if (privateFile && OperatingSystem.IsWindows())
        {
            var identity = WindowsIdentity.GetCurrent().User ?? throw new UnauthorizedAccessException();
            var access = new FileSecurity(); access.SetAccessRuleProtection(isProtected: true, preserveInheritance: false);
            access.AddAccessRule(new FileSystemAccessRule(identity, FileSystemRights.FullControl, AccessControlType.Allow));
            access.AddAccessRule(new FileSystemAccessRule(new SecurityIdentifier(WellKnownSidType.LocalSystemSid, null), FileSystemRights.FullControl, AccessControlType.Allow));
            new FileInfo(path).SetAccessControl(access);
        }
    }

    private static Dictionary<string, string> ParseOptions(string[] args)
    {
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        for (var i = 0; i < args.Length; i += 2)
        {
            if (!args[i].StartsWith("--", StringComparison.Ordinal) || args[i].Length == 2 || i + 1 >= args.Length || args[i + 1].StartsWith("--", StringComparison.Ordinal)) throw new IssuerInputException("选项须使用 --名称 值 的形式，路径中有空格时请加引号。");
            if (!values.TryAdd(args[i][2..], args[i + 1])) throw new IssuerInputException("选项重复：" + args[i]);
        }
        return values;
    }
    private static string Required(Dictionary<string, string> options, string key) => options.TryGetValue(key, out var value) && !string.IsNullOrWhiteSpace(value) ? value : throw new IssuerInputException("缺少必填选项 --" + key);
    private static void CheckOptions(Dictionary<string, string> options, string[] allowed)
    {
        var invalid = options.Keys.FirstOrDefault(x => !allowed.Contains(x, StringComparer.Ordinal));
        if (invalid is not null) throw new IssuerInputException("不支持的选项 --" + invalid);
    }

    private static void Help() => Console.WriteLine("""
        School.LicenseIssuer — 供应商离线许可证签发工具

        生成密钥：
          School.LicenseIssuer keygen --out-dir <供应商安全目录>

        签发许可证：
          School.LicenseIssuer issue --private-key <加密私钥.pem>
            --machine-code <学校端32位设备特征码>
            --resources <资源列表.json> --output <许可证.json>
            --license-id <许可证唯一编号> [--expires yyyy-MM-dd]

        密码：
          优先读取 SCHOOL_ISSUER_KEY_PASSWORD 环境变量；未设置时隐藏输入。
          keygen 交互输入需再次确认。密码不接受命令行参数，不会输出到日志。

        资源文件示例：
          [{"name":"模拟实训节点","authorizationCode":"RESOURCE-CODE","quantity":2}]

        约定：
          RSA-3072 密钥；私钥使用密码加密的 PKCS#8 PEM。
          签名使用 RSA-SHA256 / PKCS#1 v1.5，与学校端验签实现对应。
          expires 为北京时间结束日；许可证内 issuedAt / expiresAt 使用 UTC。
          未提供 expires 表示无截止日；输出文件和密钥均不覆盖已有文件。
          仅向学校配置 license-public.pem，禁止交付签发私钥和私钥密码。
          本工具供供应商单独运行，不包含在学校端 Windows 安装载荷中。

        退出码：0 成功；2 输入或格式错误；3 密钥、权限或文件操作失败。
        """);
}

internal sealed class IssuerInputException(string message) : Exception(message);
internal sealed record LicensePayload(string LicenseId, string Product, string MachineCode, DateTime IssuedAt, DateTime? ExpiresAt, List<LicenseResource> Resources);
internal sealed record LicenseResource(string Name, string AuthorizationCode, int Quantity);
internal sealed record LicenseEnvelope(string Payload, string Signature);
